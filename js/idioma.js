function normalizeTranslationKey(value) {
    return value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/\s+/g, " ").trim().toLocaleLowerCase("es");
}

const normalizedTranslations = new Map(
    Object.entries(englishTranslations).map(([source, translated]) => [normalizeTranslationKey(source), translated])
);

export function translateText(value, language) {
    if (language !== "en") return value;
    const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!match || !match[2]) return value;
    const source = match[2];
    const normalized = normalizeTranslationKey(source);
    let translated = normalizedTranslations.get(normalized);
    if (!translated) {
        const countMatch = source.match(/^Mostrando (\d+) de (\d+) (.+)$/i);
        if (countMatch) {
            const noun = normalizedTranslations.get(normalizeTranslationKey(countMatch[3])) || countMatch[3];
            translated = `Showing ${countMatch[1]} of ${countMatch[2]} ${noun}`;
        }
    }
    if (!translated) {
        const emptyMatch = source.match(/^No hay (.+) para mostrar\.$/i);
        if (emptyMatch) {
            const noun = normalizedTranslations.get(normalizeTranslationKey(emptyMatch[1]));
            if (noun) translated = `No ${noun} to display.`;
        }
    }
    if (!translated) return value;
    if (source === source.toLocaleUpperCase("es")) translated = translated.toLocaleUpperCase("en");
    return `${match[1]}${translated}${match[3]}`;
}

export function translateElement(element, language) {
    if (!element || language !== "en") return;
    if (element.nodeType === Node.TEXT_NODE) {
        if (element.parentElement && !["SCRIPT", "STYLE", "TEXTAREA"].includes(element.parentElement.tagName)) {
            element.nodeValue = translateText(element.nodeValue, language);
        }
        return;
    }
    const document = element.ownerDocument || globalThis.document;
    const walker = document.createTreeWalker(element, globalThis.NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    for (const node of textNodes) {
        const parent = node.parentElement;
        if (!parent || ["SCRIPT", "STYLE", "TEXTAREA"].includes(parent.tagName)) continue;
        if (parent.tagName === "OPTION" && !parent.hasAttribute("value")) {
            parent.value = node.nodeValue.trim();
        }
        node.nodeValue = translateText(node.nodeValue, language);
    }
    const translatableAttributes = ["aria-label", "aria-description", "placeholder", "title"];
    for (const descendant of [element, ...element.querySelectorAll("*")]) {
        for (const attribute of translatableAttributes) {
            if (descendant.hasAttribute(attribute)) {
                descendant.setAttribute(attribute, translateText(descendant.getAttribute(attribute), language));
            }
        }
    }
}
